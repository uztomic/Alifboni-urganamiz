List<LetterModel> _letters(String locale, List<List<String>> rows) {
  // rows: [character, name, exampleWord, emoji]
  return rows
      .map((r) => LetterModel(
            character: r[0],
            name: r[1],
            exampleWord: r[2],
            emoji: r[3],
            ttsLocale: locale,
          ))
      .toList();
}

